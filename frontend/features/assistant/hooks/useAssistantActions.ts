import { useRef, useState } from 'react';
import { toast } from 'sonner';

import type { ServiceCostActionResult } from '@/features/billing/types';
import { useUnauthorizedToast } from '@/lib/hooks/useUnauthorizedToast';

import { generateRecommendationsCommand } from '../dal/commands';

export function useAssistantActions() {
  const [isAutoGenerating, setIsAutoGenerating] = useState(false);
  const hasAutoGenerated = useRef(false);
  const { unauthorizedToast } = useUnauthorizedToast();

  const executeGeneration = async (isAuto: boolean): Promise<ServiceCostActionResult> => {
    try {
      const [actionError] = await generateRecommendationsCommand();

      if (actionError) {
        switch (actionError.type) {
          case 'Unauthorized': {
            unauthorizedToast();
            return 'handled-error';
          }
          case 'NoProfile': {
            toast.error('Uzupełnij profil przed wygenerowaniem rekomendacji');
            return 'handled-error';
          }
          case 'InsufficientTokens': {
            if (isAuto) {
              toast.error('Brak informacji rozliczeniowych', {
                description: 'Uzupełnij dane rozliczeniowe lub dokup tokeny.',
              });
            }
            return 'insufficient-tokens';
          }
          default: {
            if (isAuto) {
              toast.error('Błąd', {
                description: actionError.message || 'Wystąpił nieoczekiwany błąd przy generowaniu.',
              });
            }
            return 'error';
          }
        }
      }

      toast.success(
        isAuto
          ? 'Rekomendacje zostały wygenerowane pomyślnie'
          : 'Nowe rekomendacje zostały wygenerowane'
      );
      return 'success';
    } catch {
      if (isAuto) {
        toast.error('Błąd', {
          description: 'Nie udało się potwierdzić wyniku generowania rekomendacji.',
        });
      }
      return 'error';
    }
  };

  const handleGenerateNewRecommendations = () => executeGeneration(false);

  const handleAutoGenerateRecommendations = async (): Promise<ServiceCostActionResult> => {
    if (hasAutoGenerated.current) return 'handled-error';

    hasAutoGenerated.current = true;
    setIsAutoGenerating(true);

    try {
      return await executeGeneration(true);
    } finally {
      setIsAutoGenerating(false);
    }
  };

  return {
    handleGenerateNewRecommendations,
    handleAutoGenerateRecommendations,
    isAutoGenerating,
    hasAutoGenerated,
  };
}
